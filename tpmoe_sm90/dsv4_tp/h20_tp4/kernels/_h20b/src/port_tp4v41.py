"""port_tp4v41.py: H20-TP8's tp8v41.cu (DSV4.1-Flash TP8 port of h123, v41_h20 650c980) -> tp4v41.cu: DSV4.1-Flash at TP4 too.

  python3 port_tp4v41.py [tp8v41.cu] [tp4v41.cu]

TP4 (TP2_MODEL 1, TP2_NDEV 4): per-rank intermediate 2304 / 4 = 576 = 4 items of 128 + a 64-column tail item (q = 4):
  FC1  NQG 5; tail item = [gate rows 512..575 | OOB | up rows 512..575 | OOB] from the same tail maps as TP8 (there 32 real + 32 zero
       rows per 64-row block; here the block is all real rows).  The T4 split tail (32 + 32 rows in one block) is TP8-only.
  FC2  K = 576 = 18 k32 slices: NKT2 5 k-steps, the last k-tile's slices 18, 19 out of bounds (zero fill); act columns 576..639 = 0.
  AR   NRT 20 row tiles over 4 owners: owner (rtile + t) % 4 (as TP8's % 8), slot rtile / 4 (NSLOT 5).
Exact-string patches, each asserted to apply exactly as often as expected; TP2_MODEL 0 / TP2_NDEV 8 semantics unchanged."""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = Path(sys.argv[1] if len(sys.argv) > 1 else HERE / 'tp8v41.cu')
DST = Path(sys.argv[2] if len(sys.argv) > 2 else HERE / 'tp4v41.cu')
s = SRC.read_text()
n = 0


def rep(old, new, count=1):
    global s, n
    c = s.count(old)
    assert c == count, f'patch expects {count} occurrence(s), found {c}:\n{old[:300]}'
    s = s.replace(old, new)
    n += 1


rep('// tp8v41 (generated by port_v41.py from h123\'s tp4moe2_v78p12dev.cu): TP2_MODEL 0 = h123 (DeepSeek-V4-Flash), TP2_MODEL 1 =\n',
    '// tp4v41 (port_tp4v41.py on tp8v41.cu): + DeepSeek-V4.1-Flash at TP4 (TP2_MODEL 1, TP2_NDEV 4: intermediate 576 = 4 items + a 64-column\n'
    '// tail item, NKT2 5, row-tile owners (rtile + t) % 4).  tp8v41 header:\n'
    '// tp8v41 (generated by port_v41.py from h123\'s tp4moe2_v78p12dev.cu): TP2_MODEL 0 = h123 (DeepSeek-V4-Flash), TP2_MODEL 1 =\n')
rep('static_assert(TP2_MODEL == 0 || NDEV == 8, "v41: TP8 only");\n', '')
rep('#define TP2_TAIL4 (TP2_MODEL == 1)   // v41: N8 tail items as one 64-row block split 4 ways over K (maps 6, 7)',
    '#define TP2_TAIL4 (TP2_MODEL == 1 && TP2_NDEV == 8)   // v41 TP8: N8 tail items as one 64-row block split 4 ways over K (maps 6, 7)')
rep('constexpr bool T4 = TAIL && TP2_TAIL4;',
    'constexpr bool T4 = TAIL && TP2_TAIL4;\nstatic_assert(!T4 || INTER_R - INTER_M == 32, "T4 split tail: 32 + 32 rows in one block (TP8 only)");')
# reduce-scatter slot of a row tile at its owner: rtile / NDEV (TP8: >> 3, TP4: >> 2)
rep('    if constexpr (TP2_MODEL != 0) return ((size_t)(src * MAXM + t) * NSLOT + (rtile >> 3)) * NMSG + m;',
    '    if constexpr (TP2_MODEL != 0) return ((size_t)(src * MAXM + t) * NSLOT + (rtile >> (NDEV == 8 ? 3 : 2))) * NMSG + m;')
# FC2 unit: a fifth k-step (v41 TP4: K = 576 -> 5 k-tiles)
rep('''    if constexpr (NKT2 >= 4)
        kstep<N, false>(smem, full, empty, s, ph, sprev, A1, C, D, desc0 + (uint64_t)(s * (STAGE >> 4)), L.frag_off, L.scl_off, L.lane, true);
    kfinish<N>(empty, sprev, C, D, L.lane);''', '''    if constexpr (NKT2 >= 4)
        kstep<N, false>(smem, full, empty, s, ph, sprev, A1, C, D, desc0 + (uint64_t)(s * (STAGE >> 4)), L.frag_off, L.scl_off, L.lane, true);
    if constexpr (NKT2 >= 5)   // (v41 TP4: 5 k-tiles, the last one's slices 18, 19 zero-filled)
        kstep<N, false>(smem, full, empty, s, ph, sprev, A0, C, D, desc0 + (uint64_t)(s * (STAGE >> 4)), L.frag_off, L.scl_off, L.lane, true);
    static_assert(NKT2 <= 5, "FC2 k-steps");
    kfinish<N>(empty, sprev, C, D, L.lane);''')

DST.write_text(s)
print(f'{n} patches -> {DST} ({len(s.splitlines())} lines)')
