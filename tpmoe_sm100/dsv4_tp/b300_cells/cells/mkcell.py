"""Write cells/<cell>/ (adapter.py + copies of the kernel sources + README.md) for the suite harness from the current committed sources.

  python3 mkcell.py CELL v4f TP ONESHOT 'PER_M dict' [KSRC]                     KSRC = v4ft (default: port_v4f.py over tp8v41.cu) | s3
  python3 mkcell.py CELL v41tp4 4 ONESHOT 'PER_M dict' [V41CU] [COMMON tuple]   the B200 agent's v41tp4 (v41tp4t.cu: + tail stage)"""
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
S3 = ROOT / 's3'
cell, model, tp, oneshot = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]
per_m = sys.argv[5] if len(sys.argv) > 5 else '{}'
commit = subprocess.check_output(['git', '-C', str(ROOT), 'log', '-1', '--format=%h']).decode().strip()
d = HERE / cell
d.mkdir(exist_ok=True)
smodel = {'v4f': 'dsv4f', 'v41': 'dsv41f', 'v41tp4': 'dsv41f'}[model]
V41SRC = '7eaa18a'   # (suite_b200 commit of the v41tp4 copies in suite_b300b/v41tp4: c54caf3 sources, results commit 7eaa18a)


def clean(files):
    assert subprocess.call(['git', '-C', str(ROOT), 'diff', '--quiet', 'HEAD', '--', *files]) == 0, f'commit {files} first'


if model == 'v41tp4':
    v41cu = sys.argv[6] if len(sys.argv) > 6 else 'v41tp4t.cu'
    common = sys.argv[7] if len(sys.argv) > 7 else "('-DTPB2_LLS=1',)"
    files = (v41cu, 'v41tp4host.py', 'xtrace.cuh', 'port_tp4.py', 'patch_tail.py')
    clean([f'v41tp4/{f}' for f in files])
    for f in files:
        shutil.copy(ROOT / 'v41tp4' / f, d / f)
    t = (HERE / 'v41' / 'adapter.py').read_text()
    sub = dict(V41CU=v41cu, V41SRC=V41SRC, COMMON=common)
    readme = f"""# {cell} -- v41tp4 (B200 agent's kernel, run by agent B300b)

Provenance: `/home/scratch.aichenf_wwfo/suite_b200` @ {V41SRC} (LLS hardening c54caf3): `v41tp4/{v41cu}` = port_tp4.py output of tp8v41.cu
(9 full FC1 tiles, F2T tail-first FC2 with K64 tails, NDEV 4) + the tail stage `patch_tail.py` (LLS sentinel all-reduce, TAILB zeroing
guarded, gridDim trap), `v41tp4host.py` -- copied unmodified to suite_b300b/v41tp4 (suite_b300b @ {commit}) and compiled for sm_103a.
Builds: one per M, `v41tp4host.spec_flags(M, M, 4, extra={common} + PER_M[M] + ('-DTPB2_ONESHOT_MAXM={oneshot}',))`, PER_M = {per_m}.
LLS: the adapter 0xFF-fills its RS buffer's LL region once (sentinel slots, re-armed by their readers); RS buffer = RS_BYTES + TB_BYTES.
Weights: `v41tp4host.kernel_layout` of the canonical MXFP4 TP slices; `ref_partial` = `v41tp4host.ref_rank`.
Validation (suite_b300b s3bench, S3_HOST=v41tp4): ranks bitwise identical, deterministic, back-to-back eager bursts (same M and cycling all M
builds, ranks skewed) bitwise equal to isolated calls.
"""
else:
    ksrc = sys.argv[6] if len(sys.argv) > 6 else 'v4ft'
    port = {'s3': 'port_s3.py', 'v4ft': 'port_v4f.py'}[ksrc]
    files = (f'{ksrc}.cu', 's3host.py', 'xtrace.cuh', port)
    clean([f's3/{f}' for f in files])
    for f in files:
        shutil.copy(S3 / f, d / f)
    t = (HERE / 'adapter_tmpl.py').read_text()
    kdesc = {'s3': 'port_s3.py from k3_b300/L/k3h.cu',
             'v4ft': 'port_v4f.py from tp8_v41_b300/tp8v41.cu, the B300-TP8 lineage'}[ksrc]
    sub = dict(KSRC=ksrc, KDESC=kdesc)
    src_note = {'s3': """s3/s3.cu (generated by s3/port_s3.py from the read-only k3_b300/L/k3h.cu: the shape-generic patches of
tp8_v41_b300/port_v41.py + suite shapes)""",
                'v4ft': """s3/v4ft.cu (generated by s3/port_v4f.py from B300-TP8's tp8_v41_b300/tp8v41.cu = its port_v41.py over
k3h.cu + the suite_b200 tail stage: suite shapes, F2T 0 / F1F 0 (whole FC1 tiles and FC2 K chunks: the K3 FC2 path), FC2VAR 1, ACC 4, EPR
at TP8 M >= 128, LLS gridDim trap; the tp8v41 commit is in the v4ft.cu header / README of the generating run)"""}[ksrc]
    readme = f"""# {cell} -- {ksrc} (agent B300b)

Provenance: `/home/scratch.aichenf_wwfo/suite_b300b` @ {commit}: {src_note}, s3/s3host.py, xtrace.cuh -- copied here unmodified.
Shape {smodel} TP{tp} (-DS3_DIM/-DS3_IFULL/-DS3_NEXP/-DS3_NDEV from S3_MODEL={model} S3_TP={tp}, S3_KSRC={ksrc}).
Builds: one per M, `s3host.spec_flags(M, M, {tp}, extra=PER_M[M] + ('-DTPB2_ONESHOT_MAXM={oneshot}',))` (v4ft: + -DTPB2_LLS=1, NMAX 32 for
M >= 256), PER_M = {per_m}.  LLS: the adapter 0xFF-fills its RS buffer's LL region once.
Weights: `s3host.kernel_layout` of the canonical MXFP4 TP slices.  `ref_partial` = `s3host.ref_rank` (exact numerics: MXFP8 x ceil rule,
fp32 FC1, SwiGLU clamp 10, MXFP8 h floor rule, fp32 FC2 -> bf16 per slot, fp32-weighted slot sum -> bf16, rank-ordered fp32 AR -> bf16).
Validation (suite_b300b s3bench): 1-GPU s3test rel <= 6e-5 vs ref_rank; TP ranks bitwise identical, deterministic, back-to-back eager
bursts (same M and cycling all M builds, ranks skewed) bitwise equal to isolated calls.
"""
for k, v in dict(CELL=cell, MODEL=model, SMODEL=smodel, TP=tp, COMMIT=commit, ONESHOT=oneshot, PER_M=per_m, **sub).items():
    t = t.replace(f'@{k}@', v)
(d / 'adapter.py').write_text(t)
(d / 'README.md').write_text(readme)
print('wrote', d, commit)
